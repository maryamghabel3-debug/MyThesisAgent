# ---------------------------------------------------------------- تفکیک الف/ب فنتون-اکریوی
def fenton_split(text: str, tag: str) -> str:
    """استناد فنتون را به نسخهٔ الف/ب مشخص تفکیک می‌کند (هر دو قالب ویرگولی و پرانتزی)."""
    for old, new in [('فنتون-اکریوی و همکاران، ۲۰۱۲', f'فنتون-اکریوی و همکاران، ۲۰۱۲{tag}'),
                     ('فنتون-اکریوی و همکاران (۲۰۱۲)', f'فنتون-اکریوی و همکاران (۲۰۱۲{tag})')]:
        if old in text:
            return text.replace(old, new, 1)
    raise AssertionError('استناد فنتون یافت نشد!')

