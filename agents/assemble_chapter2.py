def P(n: int) -> str:
    """بازیابی پاراگراف شمارهٔ n از متن پایه (طبق قرارداد نقشهٔ جانمایی)."""
    return BASE[n + 2]

def block(*ranges):
    """چند بازهٔ پاراگرافی را پشت سر هم برمی‌گرداند."""
    out = []
    for a, b in ranges:
        out.extend(P(n) for n in range(a, b + 1))
    return out

