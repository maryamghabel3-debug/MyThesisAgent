def f2(x):
    return f'{x:.2f}'


def f3(x):
    return f'{x:.3f}'


def pstr(p):
    if p < 0.001:
        return 'p < 0.001'
    if p < 0.01:
        return 'p < 0.01'
    if p < 0.05:
        return f'p = {p:.3f}'
    return f'p = {p:.3f}'


def cronbach_alpha(items):
    it = np.asarray(items, dtype=float)
    k = it.shape[1]
    return k / (k - 1) * (1 - it.var(axis=0, ddof=1).sum() / it.sum(axis=1).var(ddof=1))


def ols(y, X):
    XtX_inv = np.linalg.inv(X.T @ X)
    b = XtX_inv @ X.T @ y
    resid = y - X @ b
    n, p_ = X.shape
    mse = resid @ resid / (n - p_)
    se = np.sqrt(np.diag(XtX_inv) * mse)
    t = b / se
    pv = 2 * stats.t.sf(np.abs(t), n - p_)
    ss_tot = ((y - y.mean()) ** 2).sum()
    return {'B': b, 'SE': se, 't': t, 'p': pv, 'R2': 1 - (resid @ resid) / ss_tot,
            'DW': np.sum(np.diff(resid) ** 2) / np.sum(resid ** 2),
            'F': ((ss_tot - resid @ resid) / (p_ - 1)) / (resid @ resid / (n - p_))}


def run():
    d = pd.read_csv(RAW)
    n_raw = len(d)

    # ---- غربالگری از پرچم‌های واقعی ----
    steps = []
    cur = d.copy()
    steps.append(('ورود به پرسشنامهٔ آنلاین', n_raw, '—'))
    m = cur['ConsentOK'] == 0
    steps.append(('حذف: عدم تکمیل یا رد رضایت آگاهانه', int(m.sum()), 'بدون رضایت معتبر'))
    cur = cur[~m]
    m = cur['MissingRate'] > 0.30
    steps.append(('حذف: پاسخ ناقص (بیش از ۳۰٪)', int(m.sum()), 'دادهٔ ناقص نظام‌مند'))
    cur = cur[~m]
    m = cur['StraightLine'] == 1
    steps.append(('حذف: الگوی پاسخ یکنواخت', int(m.sum()), 'Straight-lining'))
    cur = cur[~m]
    m = cur['ResponseTimeSec'] < 120
    steps.append(('حذف: زمان پاسخ‌دهی زیر ۱۲۰ ثانیه', int(m.sum()), 'تلاش ناکافی'))
    cur = cur[~m]
    v = cur.reset_index(drop=True)
    n = len(v)
    steps.append(('نمونهٔ نهایی معتبر', n, '—'))

    # ---- نمره‌گذاری ----
    a_sc = v[A_COLS].astype(float).copy()
    a_sc[REV_A] = 5 - a_sc[REV_A]
    v['Anxiety'] = a_sc.sum(1)
    v['Schema'] = v[S_COLS].sum(1)
    v['Risk_Behavior'] = v[R_COLS].sum(1)
    v['Edu'] = v['Education']

    o = {'n_raw': n_raw, 'n': n, 'screening': steps}

    # ---- توصیفی و زمان پاسخ ----
    rt = v['ResponseTimeSec']
    o['rt'] = {'median': float(rt.median()), 'iqr': [float(rt.quantile(.25)), float(rt.quantile(.75))],
              'max': int(rt.max())}
    o['desc'] = {}
    for nm, col in [('Anxiety', v['Anxiety']), ('Schema', v['Schema']), ('Risk', v['Risk_Behavior'])]:
        o['desc'][nm] = {'mean': col.mean(), 'sd': col.std(ddof=1), 'min': int(col.min()),
                         'max': int(col.max()), 'skew': stats.skew(col), 'kurt': stats.kurtosis(col)}

    # ---- جمعیت‌شناختی ----
    age_bins = pd.cut(v['Age'], bins=[17, 25, 35, 45, 70],
                      labels=['18-25', '26-35', '36-45', '46+']).value_counts()
    exp_bins = pd.cut(v['Experience'], bins=[0, 24, 60, 300],
                      labels=['3-24', '25-60', '61+']).value_counts()
    tr_bins = pd.cut(v['TradesPerMonth'], bins=[0, 10, 30, 200],
                     labels=['1-10', '11-30', '31+']).value_counts()
    o['demo'] = {
        'gender': v['Gender'].value_counts().reindex(['Male', 'Female']).fillna(0).astype(int).to_dict(),
        'age_bins': age_bins.to_dict(), 'age_mean': v['Age'].mean(), 'age_sd': v['Age'].std(ddof=1),
        'edu': v['Education'].value_counts().reindex(['Diploma', 'Bachelor', 'Master', 'Other']).fillna(0).astype(int).to_dict(),
        'market': v['Market'].value_counts().reindex(['Bourse', 'Crypto', 'Forex', 'Gold']).fillna(0).astype(int).to_dict(),
        'exp_bins': exp_bins.to_dict(), 'exp_mean': v['Experience'].mean(), 'exp_sd': v['Experience'].std(ddof=1),
        'tr_bins': tr_bins.to_dict(), 'tr_mean': v['TradesPerMonth'].mean(), 'tr_sd': v['TradesPerMonth'].std(ddof=1),
    }
    o['exp_tr_r'] = stats.spearmanr(v['Experience'], v['TradesPerMonth'])[0]

    # ---- پایایی ----
    o['alpha'] = {'Anxiety': cronbach_alpha(a_sc), 'Schema': cronbach_alpha(v[S_COLS]),
                  'Risk': cronbach_alpha(v[R_COLS])}
    o['alpha_domains'] = [(DOM_NAMES[i], cronbach_alpha(v[S_COLS[i * 15:(i + 1) * 15]].astype(float).values))
                          for i in range(5)]

    # ---- پیش‌فرض‌ها ----
    X = np.column_stack([v['Anxiety'], v['Schema'], v['Risk_Behavior']]).astype(float)
    Sc = np.cov(X, rowvar=False)
    Xm = X - X.mean(0)
    d2 = np.einsum('ij,jk,ik->i', Xm, np.linalg.inv(Sc), Xm)
    crit = stats.chi2.ppf(0.999, 3)
    o['maha'] = {'crit': crit, 'max': float(d2.max()), 'flagged': int((d2 > crit).sum()),
                 'near': int(((d2 > 12) & (d2 <= crit)).sum())}
    r_as = np.corrcoef(v['Anxiety'], v['Schema'])[0, 1]
    vif = 1 / (1 - r_as ** 2)
    o['vif'] = vif

    # ---- همبستگی‌ها ----
    o['corr'] = {}
    for x_, y_, key in [(v['Anxiety'], v['Risk_Behavior'], 'AR'),
                        (v['Anxiety'], v['Schema'], 'AS'),
                        (v['Schema'], v['Risk_Behavior'], 'SR')]:
        r, p = stats.pearsonr(x_, y_)
        o['corr'][key] = {'r': r, 'p': p}

    # ---- میانجی‌گری + بوت‌استرپ ۵۰۰۰ ----
    a_, s_, r_ = X[:, 0], X[:, 1], X[:, 2]
    mod_a = ols(s_, np.column_stack([np.ones(n), a_]))
    mod_b = ols(r_, np.column_stack([np.ones(n), a_, s_]))
    mod_c = ols(r_, np.column_stack([np.ones(n), a_]))
    ap, bp = mod_a['B'][1], mod_b['B'][2]
    rngb = np.random.default_rng(BOOT_SEED)
    ab, cpb, ctb = [], [], []
    for _ in range(N_BOOT):
        idx = rngb.integers(0, n, n)
        ba = ols(s_[idx], np.column_stack([np.ones(n), a_[idx]]))['B'][1]
        bb = ols(r_[idx], np.column_stack([np.ones(n), a_[idx], s_[idx]]))['B']
        bc = ols(r_[idx], np.column_stack([np.ones(n), a_[idx]]))['B'][1]
        ab.append(ba * bb[2]); cpb.append(bb[1]); ctb.append(bc)
    ct = mod_c['B'][1]
    o['med'] = {'a': ap, 'a_se': mod_a['SE'][1], 'a_t': mod_a['t'][1], 'a_p': mod_a['p'][1],
                'b': bp, 'b_se': mod_b['SE'][2], 'b_t': mod_b['t'][2], 'b_p': mod_b['p'][2],
                'cp': mod_b['B'][1], 'cp_se': mod_b['SE'][1], 'cp_t': mod_b['t'][1], 'cp_p': mod_b['p'][1],
                'c': ct, 'c_se': mod_c['SE'][1], 'c_t': mod_c['t'][1], 'c_p': mod_c['p'][1],
                'indirect': ap * bp, 'ci_ab': list(np.percentile(ab, [2.5, 97.5])),
                'ci_cp': list(np.percentile(cpb, [2.5, 97.5])), 'ci_ct': list(np.percentile(ctb, [2.5, 97.5])),
                'r2_m': mod_a['R2'], 'r2_y': mod_b['R2'], 'dw_a': mod_a['DW'], 'dw_b': mod_b['DW'],
                'prop': ap * bp / ct}
    # ---- بازه‌های تحلیلی مسیرها (B ± t.975·SE)؛ افزوده M50 (فقط افزودن) ----
    _t169 = float(stats.t.ppf(0.975, n - 2)); _t168 = float(stats.t.ppf(0.975, n - 3))
    _mm = o['med']
    _mm['ci_a_analytic'] = [_mm['a'] - _t169 * _mm['a_se'], _mm['a'] + _t169 * _mm['a_se']]
    _mm['ci_b_analytic'] = [_mm['b'] - _t168 * _mm['b_se'], _mm['b'] + _t168 * _mm['b_se']]
    _mm['ci_c_analytic'] = [_mm['c'] - _t169 * _mm['c_se'], _mm['c'] + _t169 * _mm['c_se']]
    _mm['ci_cp_analytic'] = [_mm['cp'] - _t168 * _mm['cp_se'], _mm['cp'] + _t168 * _mm['cp_se']]

    # ---- SEM ----
    o['sem'] = sem_fit(Sc, n)
    return o, v


