# ---------- SEM: الگوی مسیر با برآورد ML ----------
def implied_cov_full(theta):
    """کوواریانس ضمنی مدل میانجی‌گری کامل (بدون اثر مستقیم)."""
    a, b, vx, vem, vey = theta
    s_xx = vx
    s_mx = a * vx
    s_mm = a * a * vx + vem
    s_yx = b * a * vx
    s_ym = b * s_mm
    s_yy = b * b * s_mm + vey
    return np.array([[s_xx, s_mx, s_yx],
                     [s_mx, s_mm, s_ym],
                     [s_yx, s_ym, s_yy]])


def f_ml(theta, S):
    """تابع برازش ML؛ theta = [a, b, log(vx), log(vem), log(vey)]."""
    a, b = theta[0], theta[1]
    theta = [a, b, np.exp(theta[2]), np.exp(theta[3]), np.exp(theta[4])]
    Sig = implied_cov_full(theta)
    sign, ld = np.linalg.slogdet(Sig)
    if sign <= 0:
        return 1e6
    return ld - np.log(np.linalg.det(S)) + np.trace(S @ np.linalg.inv(Sig)) - 3


def sem_fit(S, n):
    """برازش مدل میانجی‌گری کامل و شاخص‌ها + مدل اشباع."""
    # مدل پایه (استقلال)
    D = np.diag(np.diag(S))
    F_b = np.log(np.linalg.det(D)) - np.log(np.linalg.det(S)) + np.trace(S @ np.linalg.inv(D)) - 3
    chi_b = (n - 1) * F_b
    df_b = 3  # p(p+1)/2 - p = 6-3

    # شروع از برآورد رگرسیون (واریانس‌ها در فضای لگاریتمی)
    a0 = S[0, 1] / S[0, 0]
    b0 = S[1, 2] / S[1, 1]
    x0 = np.array([a0, b0, np.log(S[0, 0]), np.log(S[1, 1] * 0.7), np.log(S[2, 2] * 0.7)])
    bnds = [(None, None), (None, None), (-8, 8), (-8, 8), (-8, 8)]
    res = minimize(f_ml, x0, args=(S,), method='L-BFGS-B', bounds=bnds,
                   options={'ftol': 1e-12, 'gtol': 1e-10, 'maxiter': 20000})
    if not res.success:
        res2 = minimize(f_ml, x0, args=(S,), method='Powell', bounds=bnds,
                        options={'xtol': 1e-12, 'ftol': 1e-12, 'maxiter': 40000})
        if res2.fun < res.fun:
            res = res2
    theta = [res.x[0], res.x[1], np.exp(res.x[2]), np.exp(res.x[3]), np.exp(res.x[4])]
    Sig = implied_cov_full(theta)
    F_m = res.fun
    chi_m = (n - 1) * F_m
    df_m = 1
    # شاخص‌ها
    tli = (chi_b / df_b - chi_m / df_m) / (chi_b / df_b - 1)
    cfi = 1 - max(chi_m - df_m, 0) / max(chi_b - df_b, chi_m - df_m)
    rmsea = np.sqrt(max(chi_m - df_m, 0) / (df_m * (n - 1)))
    # SRMR
    r = (S - Sig) / np.sqrt(np.outer(np.diag(S), np.diag(S)))
    srmr = np.sqrt((r[0, 0] ** 2 + r[1, 1] ** 2 + r[2, 2] ** 2 +
                    2 * (r[0, 1] ** 2 + r[0, 2] ** 2 + r[1, 2] ** 2)) / 6)
    return {'chi2': chi_m, 'df': df_m, 'chi2_df': chi_m / df_m, 'cfi': cfi, 'tli': tli,
            'rmsea': rmsea, 'srmr': srmr, 'theta': list(theta),
            'sat': {'chi2': 0.0, 'df': 0, 'cfi': 1.0, 'tli': 1.0, 'rmsea': 0.0, 'srmr': 0.0}}


def run_full():
    df, items = generate_all()
    n = len(df)
    rng = np.random.default_rng(1234)

    # جمعیت‌شناخت تکمیلی (فقط برای گزارش آموزشی)
    edu = rng.choice(['دیپلم', 'کارشناسی', 'کارشناسی ارشد', 'سایر'], n,
                     p=[0.25, 0.45, 0.25, 0.05])
    trades = np.clip(np.round(rng.gamma(2.0, 15, n)).astype(int) + 1, 1, 120)

    a_c, s_c, r_c = df['Anxiety'].values, df['Schema'].values, df['Risk_Behavior'].values
    out = {'n': n}

    # غربالگری (روایت آموزشی ثابت)
    out['screening'] = [('ورود به پرسشنامهٔ آنلاین', 262, '—'),
                        ('حذف: عدم تکمیل رضایت آگاهانه', 22, 'عدم احراز رضایت'),
                        ('حذف: پاسخ ناقص (بیش از ۳۰٪)', 31, 'دادهٔ ناقص'),
                        ('حذف: الگوی پاسخ یکنواخت', 17, 'Straight-lining'),
                        ('حذف: زمان پاسخ‌دهی زیر ۱۲۰ ثانیه', 12, 'تلاش ناکافی'),
                        ('نمونهٔ نهایی معتبر', 180, '—')]

    # جمعیت‌شناختی
    age_bins = pd.cut(df['Age'], bins=[17, 25, 35, 45, 65],
                      labels=['18-25', '26-35', '36-45', '46-65']).value_counts()
    exp_bins = pd.cut(df['Experience'], bins=[5, 24, 60, 120],
                      labels=['6-24', '25-60', '61-120']).value_counts()
    tr_bins = pd.cut(trades, bins=[0, 10, 30, 70, 120],
                     labels=['1-10', '11-30', '31-70', '71+']).value_counts()
    out['demo'] = {
        'gender': df['Gender'].value_counts().reindex(['Male', 'Female']).to_dict(),
        'age_bins': age_bins.to_dict(), 'age_mean': df['Age'].mean(), 'age_sd': df['Age'].std(ddof=1),
        'edu': pd.Series(edu).value_counts().reindex(['دیپلم', 'کارشناسی', 'کارشناسی ارشد', 'سایر']).to_dict(),
        'market': df['Market'].value_counts().reindex(['Bourse', 'Crypto', 'Forex', 'Gold']).to_dict(),
        'exp_bins': exp_bins.to_dict(), 'exp_mean': df['Experience'].mean(), 'exp_sd': df['Experience'].std(ddof=1),
        'tr_bins': tr_bins.to_dict(), 'tr_mean': trades.mean(), 'tr_sd': trades.std(ddof=1),
    }

    # توصیفی متغیرها
    out['desc'] = {}
    for name, col in [('Anxiety', a_c), ('Schema', s_c), ('Risk', r_c)]:
        out['desc'][name] = {'mean': col.mean(), 'sd': col.std(ddof=1), 'min': int(col.min()),
                             'max': int(col.max()), 'skew': stats.skew(col), 'kurt': stats.kurtosis(col)}

    # پایایی کل + حیطه‌های پنج‌گانهٔ طرحواره
    out['alpha'] = {k: A4.cronbach_alpha(v) for k, v in items.items()}
    dom_names = ['برش از دیگران', 'خودمختاری و عملکرد مختل', 'حدود و مرزهای مختل',
                 'دیگران‌مداری', 'فراهدشیاری و بازداری هیجانی']
    s_items = items['Schema']
    out['alpha_domains'] = [(dom_names[i], A4.cronbach_alpha(s_items[:, i * 15:(i + 1) * 15]))
                            for i in range(5)]

    # پیش‌فرض‌ها: ماهالانوبیس
    X = np.column_stack([a_c, s_c, r_c])
    Xm = X - X.mean(0)
    S_cov = np.cov(X, rowvar=False)
    d2 = np.einsum('ij,jk,ik->i', Xm, np.linalg.inv(S_cov), Xm)
    crit = stats.chi2.ppf(0.999, 3)
    out['maha'] = {'crit': crit, 'flagged': int((d2 > crit).sum()), 'max': float(d2.max())}

    # هم‌خطی
    r_xm = np.corrcoef(a_c, s_c)[0, 1]
    vif = 1 / (1 - r_xm ** 2)
    out['vif'] = vif

    # همبستگی‌ها
    out['corr'] = {}
    for x_, y_, key in [(a_c, r_c, 'AR'), (a_c, s_c, 'AS'), (s_c, r_c, 'SR')]:
        r, p = stats.pearsonr(x_, y_)
        out['corr'][key] = {'r': r, 'p': p}

    # میانجی‌گری + بوت‌استرپ ۵۰۰
    X1 = np.column_stack([np.ones(n), a_c])
    mod_a = A4.ols(s_c, X1)
    X2 = np.column_stack([np.ones(n), a_c, s_c])
    mod_b = A4.ols(r_c, X2)
    X3 = np.column_stack([np.ones(n), a_c])
    mod_c = A4.ols(r_c, X3)
    a_p, b_p = mod_a['B'][1], mod_b['B'][2]
    cp, ct = mod_b['B'][1], mod_c['B'][1]
    rngb = np.random.default_rng(BOOT_SEED)
    ab, cpb, ctb = [], [], []
    for _ in range(N_BOOT):
        idx = rngb.integers(0, n, n)
        ba = A4.ols(s_c[idx], np.column_stack([np.ones(n), a_c[idx]]))['B'][1]
        bb = A4.ols(r_c[idx], np.column_stack([np.ones(n), a_c[idx], s_c[idx]]))['B']
        bc = A4.ols(r_c[idx], np.column_stack([np.ones(n), a_c[idx]]))['B'][1]
        ab.append(ba * bb[2]); cpb.append(bb[1]); ctb.append(bc)
    out['med'] = {
        'a': a_p, 'a_se': mod_a['SE'][1], 'a_t': mod_a['t'][1], 'a_p': mod_a['p'][1],
        'b': b_p, 'b_se': mod_b['SE'][2], 'b_t': mod_b['t'][2], 'b_p': mod_b['p'][2],
        'cp': cp, 'cp_se': mod_b['SE'][1], 'cp_t': mod_b['t'][1], 'cp_p': mod_b['p'][1],
        'c': ct, 'c_se': mod_c['SE'][1], 'c_t': mod_c['t'][1], 'c_p': mod_c['p'][1],
        'indirect': a_p * b_p, 'ci_ab': list(np.percentile(ab, [2.5, 97.5])),
        'ci_cp': list(np.percentile(cpb, [2.5, 97.5])), 'ci_ct': list(np.percentile(ctb, [2.5, 97.5])),
        'r2_m': mod_a['R2'], 'f_m': mod_a['F'], 'r2_y': mod_b['R2'], 'f_y': mod_b['F'],
        'dw_a': mod_a['DW'], 'dw_b': mod_b['DW'], 'prop': a_p * b_p / ct,
    }

    # SEM
    out['sem'] = sem_fit(S_cov, n)
    return out


